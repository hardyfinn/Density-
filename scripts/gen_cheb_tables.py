#!/usr/bin/env python3
"""Generate src/dsp/ChebTables.hpp: 40 shapers, each 10 weights over Chebyshev U_1..U_10 (second kind),
normalised so max |S(x)| on [-1, 1] is 1. Families of eight: SINGLE, DECAY, ODD/EVEN, FORMANT, RANDOM.
The RANDOM family uses a fixed LCG (also implemented in tests/test_equation.cpp) so it never changes."""
import math, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def lcg(seed):
    s = seed & 0x7fffffff
    while True:
        s = (s * 1103515245 + 12345) & 0x7fffffff
        yield s / 2147483648.0

def U(n, x):
    u0, u1 = 1.0, 2.0 * x
    if n == 0: return u0
    for _ in range(n - 1):
        u0, u1 = u1, 2.0 * x * u1 - u0
    return u1

def weights(k):
    w = [0.0] * 10   # index n-1 for U_n
    if k < 8:
        w[k] = 1.0
    elif k < 16:
        p = [0.25, 0.5, 0.75, 1, 1.5, 2, 2.5, 3][k - 8]
        w = [n ** -p for n in range(1, 11)]
    elif k < 24:
        p = [0.5, 1, 1.5, 2][(k - 16) % 4]
        odd = k < 20
        w = [(n ** -p if (n % 2 == 1) == odd else 0.0) for n in range(1, 11)]
    elif k < 32:
        c = 2 + (k - 24)
        w = [math.exp(-((n - c) / 1.2) ** 2) for n in range(1, 11)]
    else:
        g = lcg(1000 + k)
        w = [(2 * next(g) - 1) * n ** -0.5 for n in range(1, 11)]
    return w

def shape(w, x):
    return sum(w[n - 1] * U(n, x) for n in range(1, 11))

NAMES = ["SINGLE"] * 8 + ["DECAY"] * 8 + ["ODD"] * 4 + ["EVEN"] * 4 + ["FORMANT"] * 8 + ["RANDOM"] * 8

def lit(v):
    t = f"{v:.9g}"
    if "." not in t and "e" not in t:
        t += ".0"
    return t + "f"

rows = []
for k in range(40):
    w = weights(k)
    m = max(abs(shape(w, -1 + 2 * i / 4096)) for i in range(4097))
    rows.append([v / m for v in w])

out = ["// Generated by scripts/gen_cheb_tables.py. Do not edit.", "#pragma once", "", "namespace dens {", "",
       "static const float CHEB_W[40][10] = {"]
for r in rows:
    out.append("\t{" + ", ".join(lit(v) for v in r) + "},")
out.append("};")
out.append("static const char* const CHEB_FAMILY[40] = {" + ", ".join(f'"{n}"' for n in NAMES) + "};")
out += ["", "} // namespace dens", ""]
open(os.path.join(ROOT, "src/dsp/ChebTables.hpp"), "w").write("\n".join(out))
print("wrote src/dsp/ChebTables.hpp")
